#!/bin/zsh
# Regenerates Render/ShaderSources.swift (inline fallback) from Render/Shaders/*.metal.
set -e
ROOT=${0:A:h}/..
R=$ROOT/Sources/Framelift/Render
OUT=$R/ShaderSources.swift
{
  echo "// GENERATED by scripts/gen_inline_shaders.sh from Render/Shaders/*.metal. Do not edit."
  echo "// Inline fallback used when the bundled Shaders resource folder cannot be found."
  echo "enum InlineShaderSources {"
  echo "    static let files: [(name: String, source: String)] = ["
  for f in $R/Shaders/*.metal; do
    echo "        (\"${f:t}\", #\"\"\""
    cat $f
    echo "\"\"\"#),"
  done
  echo "    ]"
  echo "}"
} > $OUT.tmp
if ! cmp -s $OUT.tmp $OUT; then mv $OUT.tmp $OUT; echo "updated $OUT"; else rm $OUT.tmp; fi
